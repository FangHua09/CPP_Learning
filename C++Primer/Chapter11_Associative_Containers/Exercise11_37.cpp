/*
题目：一个无序容器与其有序版本相比有何优势？有序版本有何优势？知识点：unordered_map/unordered_set（哈希无序） vs map/set（红黑树有序）
无序容器（unordered_xxx）优势
平均情况下查找、插入、删除更快：哈希表，平均 O(1)。
不需要维护元素有序，没有树平衡开销，数据量大时性能优势明显。
缺点：最坏情况哈希冲突，退化成 O(n)；元素无序；需要哈希函数；不支持范围查找（lower_bound/upper_bound）。


有序容器（map/set）优势
元素自动保持按键升序排列，可以直接按顺序遍历。
支持范围查找：lower_bound / upper_bound / equal_range，查找某个区间内的 key。
操作性能稳定：插入、删除、查找都是 O(logn)，不会出现最坏O(n)
。
可以使用比较运算符排序，不需要哈希函数，自定义类型更容易实现有序版本。
缺点：每次操作有树平衡开销，速度平均比哈希容器慢。
*/
