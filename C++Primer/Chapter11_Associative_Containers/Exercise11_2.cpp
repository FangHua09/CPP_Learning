/*
分别给出最适合使用 list、vector、deque、map 以及 set 的例子。
知识点
顺序容器：vector/list/deque；关联容器：map（key-value）、set（只有 key，去重）。

解答
vector：大量随机访问，尾部增删。例：存储采样数据，随机读取。
list：频繁在中间插入删除，很少随机访问。例：任务链表，随时插入 / 删除任务。
deque：头尾频繁增删，偶尔随机访问。例：排队队列，队头出队、队尾入队。
map：根据 key 查找，存储键值映射。例：单词计数字典，单词→出现次数。
set：保存不重复元素，快速查找是否存在。例：保存已登录用户 ID，判断用户是否在线。
*/
