/*
练习 1.14：for 循环 vs while 循环优缺点

**for 循环**

- 优点：**把初始化、循环条件、变量更新全部写在一起**，适合已知循环次数 / 确定遍历范围的场景，代码集中，可读性好，不容易忘记更新循环变量。
- 缺点：如果循环变量更新逻辑很复杂、更新语句分散在循环体内时，写在 for 头部会显得混乱。

**while 循环**

- 优点：只写循环条件，初始化和变量更新写在循环外面 / 循环体内。适合**循环次数不确定**的场景（比如等待输入，不知道要循环多少次），形式灵活。
- 缺点：初始化、更新分散在不同地方，容易漏掉更新循环变量，造成死循环。

> 
> 简单总结：**已知循环次数优先 for；循环次数未知优先 while**。
*/