
// ## 练习 1.15：熟悉编译常见错误

// “再探编译” 里常见错误类型示例：

// 1. **语法错误**：少分号、少括号、引号不配对

// ```
// std::cout << "hello"   //少分号，编译报错
// ```

// 2. **变量未定义**：使用没有声明的变量

// ```
// int main(){
//     a = 10; //a没有定义
//     return 0;
// }
// ```

//3. **拼写错误**：标识符写错，例如 `cout`写成`count`，`std::`漏掉。

//4. **注释不闭合**：块注释`/*`没有写*/

//写一个包含多种错误的测试程序，编译，观察编译器给出的报错行号、错误提示，读懂提示信息，再逐个修正。
