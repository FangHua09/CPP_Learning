/*
题目描述：在调用 factorial 函数时，为什么我们传入的值是 val‑1 而非 val‑‑？
解答
val‑1：表达式计算 val‑1，val 本身不变，把计算结果作为实参传给下一层递归。
val‑‑：后置递减，先使用 val 当前值作为实参，函数调用结束之后才把 val 减一。

factorial(val--)等价于：
factorial(val); //传入没有减1的val
val = val -1;
递归永远传入同样 val 值，无限递归，栈溢出崩溃。

如果写成--val前置递减是可以，但会修改当前函数内局部 val 变量，可读性差，不推荐。
核心知识点
区分：val‑1（不改变变量）；后置val--；前置--val。
*/