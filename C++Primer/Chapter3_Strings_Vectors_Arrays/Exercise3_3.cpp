// **题目描述**：请说明 string 类的输入运算符和 getline 函数分别是如何处理空白字符的。
/*
1. **string 输入运算符 `cin >> s`**
   - 会**跳过开头所有空白字符**（空格、换行符、制表符）；
   - 从第一个非空白字符开始读取；
   - 读到下一处空白字符就停止；
   - 空白字符留在输入缓冲区，不会存入字符串。> 
   > 作用：读取一个单词。

   
2. **getline(cin, s)**
   - 不跳过开头空白；
   - 读取输入，直到遇到 ** 换行符`\n`** 为止；
   - 将读到的所有字符（包含中间空格、制表符）存入字符串；
   - **丢弃末尾换行符**，换行不会保存到 s 中。> 
   > 作用：读取一整行文本。
*/