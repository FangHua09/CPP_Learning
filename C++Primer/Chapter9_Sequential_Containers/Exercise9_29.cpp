/*
题目描述
假定 vec 包含 25 个元素，那么 vec.resize(100)会做什么？如果接下来调用 vec.resize(10)会做什么？

解答
resize(n) 的作用是修改容器的有效元素个数：
vec.resize(100)：原容器有 25 个元素，目标大小 100 大于当前大小。会在容器末尾追加 75 个值初始化的新元素，容器有效元素总数变为 100。
接着执行 vec.resize(10)：目标大小 10 小于当前大小 100。会删除容器末尾的 90 个元素，只保留最前面 10 个元素，容器有效元素总数变为 10。
注意：resize 只改变元素数量，不一定改变容器内存容量capacity()。
*/