/*
题目描述：对于下面的程序任务，vector、deque 和 list 哪种容器最为适合？
解释你的选择的理由。如果没有哪一种容器优于其他容器，也请解释理由。
(a) 读取固定数量的单词，将它们按字典序插入到容器中。我们将在下一章中看到，关联容器更适合这个问题。

(b) 读取未知数量的单词，总是将新单词插入到末尾。删除操作在头部进行。

(c) 从一个文件读取未知数量的整数。将这些数排序，然后将它们打印到标准输出。

(a) 读取固定数量单词，按字典序插入容器
适合：list理由：按字典序插入意味着在容器中间位置频繁插入元素。
vector：中间插入会移动大量元素，效率很低；
deque：中间插入同样需要移动元素，代价大；
list是双向链表，迭代器定位后中间插入只修改指针，不会拷贝移动数据，插入效率高。
注：题目提示关联容器（set）更适合有序存放，本题只在 vector/deque/list 三者选择。

(b) 新单词插入末尾，删除操作在头部
适合：deque理由：
deque：尾部插入、头部删除都是 O (1) 常数时间，正是 deque 的优势场景。
vector：头部删除会移动全部元素，性能差；尾插效率尚可，但头删不行。
list：头删尾插虽然也可以，但相比 deque 额外的链表指针开销更大，随机访问差。

(c) 读取整数，排序，输出
适合：vector理由：需要调用排序算法 sort。标准库 sort 需要随机访问迭代器。
vector 支持随机访问迭代器，sort 效率最高；内存连续。
deque 虽然也支持随机访问，但内存分段，sort 性能弱于 vector。
list 不支持随机访问迭代器，不能直接用通用sort，只能使用自己的成员sort。读取后只需要排序 + 遍历输出，不需要头尾 / 中间插入删除，vector是最优。

核心要点总结
频繁中间插入：优先list；
频繁头 + 尾增删：优先deque；
需要排序、随机访问：优先vector。
*/