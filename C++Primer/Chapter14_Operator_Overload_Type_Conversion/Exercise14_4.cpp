/*
 *判断运算符是否应该作为类成员
 成员运算符判断口诀：
 必须成员：=、()、[]、->（赋值、调用、下标、箭头）
 推荐成员：复合赋值 += -= *= /= %=
 必须非成员：<< >>
 其余（+ - == &&）推荐非成员，保证左右操作数隐式转换对称。
 (a) %：普通二元算术，非成员（一般用复合赋值 %= 实现）
 (b) %=：复合赋值，成员函数
 (c) ++：自增运算符，成员函数（前置 / 后置都成员）
 (d) ->：箭头运算符，必须成员，不能重载为非成员
 (e) <<：输出流，必须非成员，第一个参数 ostream
 (f) &&：逻辑与，非成员；重载 && 没有短路求值，一般不推荐重载
 (g) ==：相等比较，非成员（保证左右操作数转换对称）
 (h) ()：函数调用运算符，必须成员
 */

