/*
 *问题：C++11 为什么引入 lambda？什么时候用 lambda，什么时候用函数对象类？
 答案
 为什么引入 lambda
 lambda 本质是就地定义的匿名仿函数。
 不用单独写一个完整类，代码紧凑，写在调用算法的地方，逻辑直观；
 可以方便捕获局部变量（值捕获 / 引用捕获）；
 临时、一次性使用的谓词，不用单独定义类，减少代码量。
 什么时候用 lambda，什么时候用自定义仿函数类
 ✅ 用 lambda：
 谓词只使用一次，逻辑简短；
 需要捕获当前函数局部变量；
 谓词逻辑紧贴算法调用处，希望代码可读性高。
 ✅ 用仿函数类（自定义 class+operator ()）：
 同一个判断逻辑多处复用，多个地方算法都要用这个谓词；
 需要保存多个状态成员（不止捕获一两个变量）；
 比较复杂的谓词逻辑，需要构造函数、多个成员变量；
 需要可以跨函数、跨作用域传递这个谓词对象。
 一句话总结：一次性短逻辑用 lambda；需要复用、带复杂状态，就写函数对象类。
 */

