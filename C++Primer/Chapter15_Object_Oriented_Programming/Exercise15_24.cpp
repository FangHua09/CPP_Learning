/*
 *问题 1：哪种类需要虚析构函数？
 当一个类打算作为基类，并且希望通过基类指针 / 引用删除派生类对象时，这个基类应该定义虚析构函数。
 场景举例：
 cpp
 Base *p = new Derived();
 delete p; // 如果Base析构不是虚函数，只会调用Base的析构，Derived析构不会执行 → 内存泄漏
 简单记：只要类有虚函数，一般就应该给它虚析构函数。
 问题 2：虚析构函数必须执行什么样的操作？
 析构顺序：销毁对象时，先执行派生类的析构函数，再执行基类的析构函数。
 delete一个基类指针指向派生类对象时，虚析构保证动态绑定，首先调用派生类析构，再自动调用基类析构。
 虚析构函数本身的函数体操作：释放当前类自己拥有的资源；派生类析构负责释放派生类新增资源。
 不需要手动调用父类析构，编译器自动调用。
 补充一句话考点
 虚析构函数的目的：保证通过基类指针销毁派生类对象时，完整释放派生类和基类的所有资源，防止内存泄漏。
 */
