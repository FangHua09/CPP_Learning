/*
友元什么时候有用？列出友元的利与弊
友元适用场景当一个非成员函数（或者另一个类）需要访问类的private私有成员，但又不适合作为类的成员函数时，可以把它声明为友元。典型例子：read、print、add这类 Sales_data 非成员函数，需要直接访问私有数据；运算符重载也经常使用友元。
✅优点
允许外部函数 / 其他类访问本类私有成员，不用把内部数据暴露为public；
可以保持函数为非成员函数（运算符重载时非成员友元形式更合适）；
简化代码，不用写一堆 getter 接口只为了给某个函数使用。

❌弊端
破坏封装性：友元可以直接访问私有成员，绕过类的公有接口；过多友元会削弱数据隐藏。
友元声明不是类接口，友元关系不能继承、不能传递：A 是 B 友元，B 是 C 友元，A 并不会自动成为 C 友元。
滥用友元会增大耦合，类内部修改，所有友元函数都可能受影响，维护成本上升。
总结：友元是为特殊场景设计的，尽量少用。
*/