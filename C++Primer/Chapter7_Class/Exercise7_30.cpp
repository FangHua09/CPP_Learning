/*
显式用this->访问成员的优缺点示例：this->cursor = r * width + c;

✅优点
区分同名局部变量与成员变量：当函数参数 / 局部变量名字和类成员重名，this->成员名明确指定访问类成员，消除名字遮蔽。
cpp
运行
void set_cursor(pos cursor)
{
    this->cursor = cursor; // this->cursor是成员；右边cursor是形参
}
阅读代码时明确：这是对象的成员，不是局部变量；复杂代码可读性提升。

❌缺点
成员名与局部变量不冲突时，写this->属于多余代码，代码冗余，增加视觉负担。
代码啰嗦，大多数场景不需要；滥用降低简洁度。
总结：只有发生名字冲突时才建议写 this->；平时直接写成员名即可。
*/