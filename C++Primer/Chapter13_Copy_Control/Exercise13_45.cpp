/*
练习 13.45：解释右值引用和左值引用的区别
左值引用：T&，绑定左值。左值：有持久状态、有名字、可以取地址的对象。
右值引用：T&&，绑定右值。右值：临时对象、即将销毁的对象，没有名字，不能取地址。

核心区别：
绑定对象不同
左值引用（T&）：只能绑定左值；const T&可以绑定左值 + 右值。
右值引用（T&&）：只能绑定右值，不能绑定普通左值。

语义
左值引用：引用一个还在使用、存活持久的对象。
右值引用：引用临时对象 / 即将销毁的对象，可以安全地 “偷” 资源（移动语义，不用拷贝）。
变量本身是左值：哪怕变量类型是int&&，这个变量名字本身也是左值。
一句话：左值引用绑定到有名字的对象；右值引用绑定到临时对象。
*/
