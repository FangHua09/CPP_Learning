/*
原错误代码：
string s = "word";
string pl = s + s[s.size() - 1] == 's' ? "" : "s" ;
❌编译报错。运算符优先级：+高于==，==高于条件运算符?:

等价于：
string pl = ((s + s[s.size()-1]) == 's') ? "" : "s";
问题：
先执行s + s[...]做字符串拼接，得到一个完整 string 对象；
拿整个拼接后的 string 和字符字面量's'用==对比；string不能直接和char比较，编译错误。
原意：判断s最后一个字符是不是s；如果不是，字符串末尾追加s。
✅修改方案，加括号限定条件运算范围：
string pl = s + ( s[s.size()-1] == 's' ? "" : "s" );
*/