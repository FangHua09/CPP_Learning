/*
**题目**：计算按揭贷款时，对于利率、本金和付款分别应选择何种数据类型？说明你的理由。

**答案**

- **本金**：`long long`理由：本金是整数（以分为单位存储，避免浮点数误差），房屋贷款金额数值可以很大，int 范围不够；`long long`64 位整数，足够容纳大额金额。

> 
> 不建议直接用浮点存本金，浮点会存在精度丢失。

- **利率**：`double`理由：利率是小数，例如 4.25%；需要小数，并且要求较高精度，`double`双精度浮点精度足够；float 精度不足容易累积误差。
- **每期付款**：`double`理由：每期还款额会包含小数（元、角、分），涉及利率乘法运算，需要高精度浮点；选用`double`避免计算误差。

> 
> 补充：实际金融生产环境会用定点数 / 专门十进制库，C++ 基础没有内置十进制小数，习题场景下使用`double`。

*/