/*
 *这段循环来自StrVec::reallocate（扩容函数），作用是：把旧内存空间里的所有元素，逐个移动构造到新分配的更大内存空间中，完成扩容迁移。
 cpp
 for (size_t i = 0; i != size(); ++i)
     alloc.construct(dest++, std::move(*elem++));
 逐部分解释
 循环控制：遍历旧空间中全部size()个元素，逐个迁移。
 dest++：指向新内存中当前待构造的位置；构造完成后指针向后移动一位。
 *elem++：解引用旧空间迭代器，得到当前元素（是左值）；随后迭代器向后移动。
 std::move(*elem++)
 std::move的作用：强制把左值转换为右值引用。
 目的：告诉alloc.construct，可以使用移动构造函数来创建新对象，直接把旧元素的底层资源（比如string的字符数组、内存指针）转移给新对象。
 alloc.construct(地址, 初值)：分配器在指定内存地址上，调用对应构造函数初始化对象。
 */
