/*
练习 16.66：重载 debug_rep VS 模板特例化，优缺点
✅函数重载方案
优点
重载解析规则简单直观，优先匹配更合适的重载；
支持隐式类型转换；
阅读和调试更容易。
缺点
重载集是独立函数，不是模板体系的一部分；
无法限制只针对模板的类型；当重载和模板一起存在时，重载优先于模板实例。
✅模板特例化方案
优点
属于模板体系，专门为主模板提供特殊类型的定制实现；
模板的名字查找和模板参数推导规则统一。
缺点
不支持隐式类型转换；模板推导必须精确匹配；
只能针对已经存在的主模板；不能凭空新增函数；
语法晦涩，只能全特例化（C++17 前函数模板不能部分特例化）。
核心考点：重载是独立函数；特例化只是主模板针对特定类型的替换实现。
*/