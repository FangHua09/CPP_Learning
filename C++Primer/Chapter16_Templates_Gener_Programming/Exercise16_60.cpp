/*
 *练习 16.60：解释 make_shared 如何工作
 make_shared<T>(args...)是可变参数模板函数：
 接收构造 T 所需的任意参数包，使用完美转发；
 一次性分配一块内存：这块内存同时存放 T 对象 + shared_ptr 的控制块（引用计数、弱引用计数）；
 在分配好的内存中，就地构造 T 对象（placement new）；
 返回一个shared_ptr<T>，指向这个新对象。
 优点：
 只一次内存分配（普通shared_ptr<T>(new T())是两次分配：new 对象一次，控制块又一次）；
 异常安全：不会出现内存泄漏。
 注意：控制块和对象放在同一块内存，所以当 weak_ptr 存在时，对象内存不会被释放，直到 weak 计数也归零。
 */
